import { describe, expect, it } from 'vitest';
import { fixtureRepo, lanes, read, write } from './helpers.js';

const ev = (ts: string, task: string, agent: string, status: string, note = '') => JSON.stringify({ ts, task, agent, status, note, flags: [] });

function seed(dir: string) {
  write(
    dir,
    'agents/board.jsonl',
    [
      ev('2026-11-01T10:00:00Z', 'T-1', 'cursor', 'TODO'),
      ev('2026-11-01T11:00:00Z', 'T-1', 'cursor', 'DOING'),
      ev('2026-11-02T10:00:00Z', 'T-2', 'claude-code', 'DOING', 'deploy prep'),
      ev('2026-11-03T10:00:00Z', 'T-1', 'cursor', 'REVIEW', 'ready'),
      ev('2026-11-04T10:00:00Z', 'T-3', 'cursor', 'DONE'),
      'not json',
      ev('2026-11-05T10:00:00Z', 'T-4', 'codex-2', 'STOPPED'),
    ].join('\n') + '\n',
  );
}

describe('board', () => {
  it('shows open tasks only, deduped (latest wins), newest first', () => {
    const dir = fixtureRepo();
    seed(dir);
    const r = lanes(dir, ['board']);
    expect(r.code).toBe(0);
    const lines = r.out.trim().split('\n');
    expect(lines).toHaveLength(2);
    expect(lines[0]).toMatch(/^T-1\s+REVIEW\s+cursor\s+2026-11-03 10:00\s+ready$/);
    expect(lines[1]).toMatch(/^T-2\s+DOING\s+claude-code/);
    expect(r.err).toMatch(/line 6 is not JSON/);
  });

  it('--all includes DONE and STOPPED', () => {
    const dir = fixtureRepo();
    seed(dir);
    const r = lanes(dir, ['board', '--all']);
    expect(r.out).toMatch(/T-3\s+DONE/);
    expect(r.out).toMatch(/T-4\s+STOPPED/);
  });

  it('--json gives machine output; filters work', () => {
    const dir = fixtureRepo();
    seed(dir);
    const j = JSON.parse(lanes(dir, ['board', '--json']).out);
    expect(j.tasks.map((t: any) => t.task)).toEqual(['T-1', 'T-2']);
    expect(j.tasks[0]).toMatchObject({ status: 'REVIEW', holder: 'cursor', reviewBy: 'cursor' });
    expect(j.tasks[0].history).toBeUndefined();
    expect(lanes(dir, ['board', '--agent', 'claude-code']).out).not.toContain('T-1');
    expect(lanes(dir, ['board', '--status', 'review']).out).not.toContain('T-2');
  });

  it('gen writes the same rows to agents/BOARD.md; --md prints it', () => {
    const dir = fixtureRepo();
    seed(dir);
    lanes(dir, ['gen']);
    const md = read(dir, 'agents/BOARD.md');
    expect(md).toContain('<!-- generated by lanes, do not edit -->');
    expect(md.indexOf('| T-1 | REVIEW')).toBeGreaterThan(0);
    expect(md.indexOf('| T-1 |')).toBeLessThan(md.indexOf('| T-2 |'));
    expect(md).not.toContain('T-3');
    expect(md.match(/\| T-1 \|/g)).toHaveLength(1);
    expect(lanes(dir, ['board', '--md']).out).toContain('| T-1 | REVIEW | cursor |');
  });

  it('lists resource locks', () => {
    const dir = fixtureRepo();
    lanes(dir, ['lock', 'sandbox', '--as', 'cursor']);
    expect(lanes(dir, ['board']).out).toMatch(/lock sandbox: cursor until/);
  });
});
