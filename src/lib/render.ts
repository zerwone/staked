import * as path from 'node:path';
import { Repo } from './context.js';
import { boardState, BoardEvent, handoverEvents, isOpen, readBoard, sortedTasks, TaskState } from './board.js';
import { Question, questionState, readQuestionEvents } from './questions.js';
import { Agent, loadRoles, Roles } from './roles.js';
