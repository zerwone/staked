import { listFiles, sha256, truncate, writeIfChanged, readText } from './util.js';

export const MARKER = '<!-- generated by lanes, do not edit -->';
const HASH_RE = /^<!-- lanes:sha256=([0-9a-f]{16}) -->$/m;
export const CONTEXT_LIMIT = 6000; // bytes; the spec target is "< 6 KB"

export const VENDOR_FILES = ['CLAUDE.md', 'AGENTS.md', '.cursor/rules/lanes.mdc', 'GEMINI.md'] as const;
export const VIEW_FILES = ['agents/BOARD.md', 'agents/HISTORY.md'] as const;

/** Stamp a generated document: marker line + content hash so hand edits are detectable. */
export function stamp(body: string, preamble = ''): string {
  const content = preamble + MARKER + '\n' + body;
  const h = sha256(content).slice(0, 16);
  return preamble + MARKER + '\n' + `<!-- lanes:sha256=${h} -->\n` + body;
}

export type GenStatus = 'ok' | 'edited' | 'not-generated';

export function verifyGenerated(text: string): GenStatus {
  const norm = text.replace(/\r\n/g, '\n');
  if (!norm.includes(MARKER)) return 'not-generated';
  const m = HASH_RE.exec(norm);
  if (!m) return 'edited';
  const without = norm.replace(m[0] + '\n', '');
  return sha256(without).slice(0, 16) === m[1] ? 'ok' : 'edited';
}

export function contextFilesFor(a: Agent): string[] {
  if (a.context && a.context.length) return a.context;
  const n = a.name.toLowerCase();
  if (n.startsWith('claude')) return ['CLAUDE.md'];
  if (n.startsWith('cursor')) return ['.cursor/rules/lanes.mdc'];
  if (n.startsWith('gemini')) return ['GEMINI.md'];
  return ['AGENTS.md'];
}

export interface Model {
  roles: Roles;
  state: Map<string, TaskState>;
  events: BoardEvent[];
  questions: Map<string, Question>;
  specs: { file: string; agent: string; task: string; status: string }[];
}

export function loadModel(repo: Repo): Model {
  const roles = loadRoles(repo);
  const { events } = readBoard(repo);
  const state = boardState(events);
  const questions = questionState(readQuestionEvents(repo).rows);
  return { roles, state, events, questions, specs: listSpecs(repo) };
}

export function listSpecs(repo: Repo) {
  const out: Model['specs'] = [];
  const base = path.join(repo.agents, 'inbox');
  for (const rel of listFiles(base, (r) => r.endsWith('.md'))) {
    const parts = rel.split('/');
    const agent = parts.length > 1 ? parts[0] : '';
    const fm = readFrontmatter(readText(path.join(base, rel)) ?? '');
    const d = fm.data ?? {};
    out.push({
      file: `agents/inbox/${rel}`,
      agent,
      task: typeof d.task === 'string' ? d.task : path.basename(rel, '.md'),
      status: typeof d.status === 'string' ? d.status : '',
    });
  }
  return out;
}

function lane(a: Agent) {
  return a.lane.length ? a.lane.map((g) => '`' + g + '`').join(', ') : '(none)';
}

function date(ts: string) {
  return ts.replace('T', ' ').replace(/:\d{2}(\.\d+)?Z$/, 'Z');
}

function taskLine(t: TaskState, noteLen: number) {
  const note = t.note ? ' — ' + truncate(t.note, noteLen) : '';
  return `${t.task} ${t.status} (${t.agent}, ${date(t.ts)})${note}`;
}

function questionLine(q: Question, textLen: number) {
  const blocks = q.blocking.length ? ` blocks ${q.blocking.join(',')};` : '';
  const def = q.default ? ` default: ${truncate(q.default, 60)};` : '';
  const exp = q.expires ? ` expires ${q.expires.slice(0, 10)}` : '';
  return `${q.id} (${q.agent};${blocks}${def}${exp}) ${truncate(q.text, textLen)}`.replace(/;\)/, ')');
}

interface Caps {
  myTasks: number;
  myQuestions: number;
  team: number;
  note: number;
  qtext: number;
}

function agentSection(a: Agent, m: Model, caps: Caps, single: boolean): string {
  const r = m.roles;
  const lines: string[] = [];
  lines.push(single ? `## You are \`${a.name}\`` : `## If you are \`${a.name}\``);
  lines.push('');
  lines.push(`- Status: **${a.status}**${a.status !== 'active' ? ' — do not claim new work' : ''}`);
  lines.push(`- Your lane (the only paths you may change): ${lane(a)}`);
  if (a.reviews.length) lines.push(`- You review: ${a.reviews.join(', ')}`);
  const reviewers = Object.values(r.agents).filter((x) => x.reviews.includes(a.name) && x.status === 'active').map((x) => x.name);
  if (reviewers.length) lines.push(`- Reviewed by: ${reviewers.join(', ')}`);
  for (const [k, v] of Object.entries(a.extra)) lines.push(`- ${k}: ${typeof v === 'object' ? JSON.stringify(v) : String(v)}`);
  if (r.boss === a.name) lines.push('- You are the **boss**: you write specs in `agents/inbox/<agent>/` and keep roles.yml current via `lanes handover`.');

  const mine = sortedTasks(m.state).filter((t) => t.holder === a.name || (t.agent === a.name && isOpen(t)));
  lines.push('', '### Your open tasks', '');
  if (!mine.length) lines.push('- none. Claim one with `npx lanes claim <task> --as ' + a.name + '`.');
  for (const t of mine.slice(0, caps.myTasks)) lines.push('- ' + taskLine(t, caps.note));
  if (mine.length > caps.myTasks) lines.push(`- …${mine.length - caps.myTasks} more: \`npx lanes board\``);

  const specs = m.specs.filter((s) => s.agent === a.name && s.status === 'open');
  if (specs.length) {
    lines.push('', '### Your open specs', '');
    for (const s of specs.slice(0, caps.myTasks)) lines.push(`- ${s.task}: \`${s.file}\``);
    if (specs.length > caps.myTasks) lines.push(`- …${specs.length - caps.myTasks} more in \`agents/inbox/${a.name}/\``);
  }

  const myTaskIds = new Set(mine.map((t) => t.task));
  const qs = [...m.questions.values()].filter((q) => q.status === 'open' && (q.agent === a.name || q.blocking.some((t) => myTaskIds.has(t))));
  lines.push('', '### Open questions you own', '');
  if (!qs.length) lines.push('- none');
  for (const q of qs.slice(0, caps.myQuestions)) lines.push('- ' + questionLine(q, caps.qtext));
  if (qs.length > caps.myQuestions) lines.push(`- …${qs.length - caps.myQuestions} more: \`npx lanes questions open\``);
  return lines.join('\n');
}

function howTo(single: string | null): string {
  const me = single ?? '<you>';
  return [
    '## How to work',
    '',
    `- Identify yourself on every command: \`--as ${me}\`, or set \`LANES_AGENT=${me}\`, or \`git config user.name ${me}\` in your worktree.`,
    '- Read state through the CLI only: `npx lanes board`, `npx lanes questions open`. Never load `agents/board.jsonl` or `agents/questions.jsonl` raw.',
    `- Start: \`npx lanes claim <task> --as ${me}\`. Shared resources: \`npx lanes lock <resource> --as ${me} --ttl 2h\`, then \`npx lanes unlock <resource> --as ${me}\`.`,
    `- Need the owner: \`npx lanes ask --as ${me} --text "..." --blocking <task> --default "..." --expires 2d\`. Keep working on the default if it is safe.`,
    `- Finish: write \`agents/reports/<task>-${me}.md\` with frontmatter \`task, agent, flags, tests_run, native_boot, files_changed\`, then \`npx lanes status <task> REVIEW --as ${me}\`.`,
    '- Owner decisions live only in `agents/DECISIONS.md` (D-001, D-002, …). Cite the number; never restate a decision elsewhere.',
    '- Specs: `agents/inbox/<agent>/`. Shared interface contracts: `agents/specs/` (change them there first).',
    '- The pre-commit hook (`lanes check`) refuses commits outside your lane.',
    '- Three failed attempts at the same step: stop, write the report, set the task BLOCKED.',
  ].join('\n');
}

export function renderContext(file: string, agents: Agent[], m: Model, caps: Caps): string {
  const r = m.roles;
  const parts: string[] = [];
  const single = agents.length === 1 ? agents[0].name : null;
  parts.push('# Team context (lanes)');
  parts.push('');
  parts.push('Generated from `agents/roles.yml`, `agents/board.jsonl`, `agents/questions.jsonl` and spec frontmatter. Do not edit: change the sources and run `npx lanes gen`.');
  parts.push('');
  parts.push(`Owner: **${r.owner}** · Boss: **${r.boss || r.owner}**`);
  parts.push('');
  parts.push('## Rules');
  parts.push('');
  r.rules.forEach((x, i) => parts.push(`${i + 1}. ${x}`));
  parts.push('');
  if (!agents.length) {
    parts.push('No agent in `agents/roles.yml` reads this file. Find your name below and use `npx lanes board`.');
    parts.push('');
  }
  for (const a of agents) {
    parts.push(agentSection(a, m, caps, !!single));
    parts.push('');
  }
  const others = Object.values(r.agents).filter((a) => !agents.includes(a) && a.status !== 'retired');
  if (others.length) {
    parts.push('## Other agents (do not touch their lanes)');
    parts.push('');
    for (const a of others) parts.push(`- ${a.name} (${a.status}): ${lane(a)}`);
    parts.push('');
  }
  if (r.resources.length) {
    parts.push(`Lockable resources: ${r.resources.map((x) => '`' + x + '`').join(', ')}. Lock before use.`);
    parts.push('');
  }
  const mineIds = new Set(agents.map((a) => a.name));
  const team = sortedTasks(m.state).filter((t) => !mineIds.has(t.holder ?? '') && !mineIds.has(t.agent));
  if (caps.team > 0 && team.length) {
    parts.push('## Rest of the board');
    parts.push('');
    for (const t of team.slice(0, caps.team)) parts.push('- ' + taskLine(t, caps.note));
    if (team.length > caps.team) parts.push(`- …${team.length - caps.team} more: \`npx lanes board\``);
    parts.push('');
  }
  parts.push(howTo(single));
  parts.push('');
  const body = parts.join('\n');
  const preamble = file.endsWith('.mdc') ? '---\ndescription: lanes team context (roles, lanes, open tasks, rules)\nalwaysApply: true\n---\n' : '';
  return stamp(body, preamble);
}

const CAP_STEPS: Caps[] = [
  { myTasks: 10, myQuestions: 8, team: 10, note: 80, qtext: 120 },
  { myTasks: 8, myQuestions: 6, team: 5, note: 60, qtext: 90 },
  { myTasks: 5, myQuestions: 4, team: 0, note: 50, qtext: 70 },
  { myTasks: 3, myQuestions: 3, team: 0, note: 40, qtext: 50 },
  { myTasks: 2, myQuestions: 2, team: 0, note: 0, qtext: 40 },
];

/** Render with progressively tighter caps until the file fits the size target. */
export function renderContextFitted(file: string, agents: Agent[], m: Model): string {
  let out = '';
  for (const caps of CAP_STEPS) {
    out = renderContext(file, agents, m, caps);
    if (Buffer.byteLength(out) < CONTEXT_LIMIT) return out;
  }
  return out;
}

export function renderBoard(m: Model): string {
  const open = sortedTasks(m.state);
  const lines = [
    '# Board',
    '',
    'Open tasks, newest first; one row per task (latest event wins). Source: `agents/board.jsonl`. Closed tasks: `npx lanes board --all`.',
    '',
  ];
  if (!open.length) lines.push('_No open tasks._');
  else {
    lines.push('| task | status | agent | since | note |', '| --- | --- | --- | --- | --- |');
    for (const t of open) {
      lines.push(`| ${t.task} | ${t.status} | ${t.agent} | ${date(t.ts)} | ${truncate(t.note, 100).replace(/\|/g, '\\|')} |`);
    }
  }
  lines.push('');
  return stamp(lines.join('\n'));
}

export function renderHistory(m: Model): string {
  const hs = handoverEvents(m.events);
  const lines = ['# History', '', 'One line per handover. Source: handover events in `agents/board.jsonl`.', ''];
  if (!hs.length) lines.push('_No handovers yet._');
  for (const h of hs) {
    const what: string[] = [];
    if (h.lanes.length) what.push('lanes ' + h.lanes.join(', '));
    if (h.boss) what.push('boss');
    if (h.released?.length) what.push('paused ' + h.released.join(', '));
    lines.push(`- ${date(h.ts)} ${h.from} → ${h.to}: ${what.join('; ') || 'no change'} (by ${h.by})`);
  }
  lines.push('');
  return stamp(lines.join('\n'));
}

export interface GenPlan {
  file: string;
  content: string;
}

export function planGen(repo: Repo, m?: Model): GenPlan[] {
  const model = m ?? loadModel(repo);
  const byFile = new Map<string, Agent[]>();
  byFile.set('AGENTS.md', []);
  for (const a of Object.values(model.roles.agents)) {
    if (a.status === 'retired') continue;
    for (const f of contextFilesFor(a)) {
      if (!byFile.has(f)) byFile.set(f, []);
      byFile.get(f)!.push(a);
    }
  }
  const plans: GenPlan[] = [];
  for (const [file, agents] of byFile) plans.push({ file, content: renderContextFitted(file, agents, model) });
  plans.push({ file: 'agents/BOARD.md', content: renderBoard(model) });
  plans.push({ file: 'agents/HISTORY.md', content: renderHistory(model) });
  return plans;
}

export interface GenResult {
  written: string[];
  unchanged: string[];
  removed: string[];
  refused: string[];
  sizes: Record<string, number>;
}

export function runGen(repo: Repo, opts: { force?: boolean; dryRun?: boolean } = {}): GenResult {
  const plans = planGen(repo);
  const res: GenResult = { written: [], unchanged: [], removed: [], refused: [], sizes: {} };
  for (const p of plans) {
    const abs = repo.p(p.file);
    const cur = readText(abs);
    res.sizes[p.file] = Buffer.byteLength(p.content);
    if (cur !== null && verifyGenerated(cur) === 'not-generated' && !opts.force) {
      res.refused.push(p.file);
      continue;
    }
    // core.autocrlf on Windows checks files out with CRLF: same content, not a change
    const same = cur !== null && cur.replace(/\r\n/g, '\n') === p.content;
    if (opts.dryRun || same) {
      (same ? res.unchanged : res.written).push(p.file);
      continue;
    }
    if (writeIfChanged(abs, p.content)) res.written.push(p.file);
    else res.unchanged.push(p.file);
  }
  // remove vendor files lanes generated earlier that no agent reads any more
  const targets = new Set(plans.map((p) => p.file));
  for (const f of VENDOR_FILES) {
    if (targets.has(f)) continue;
    const abs = repo.p(f);
    const cur = readText(abs);
    if (cur !== null && verifyGenerated(cur) !== 'not-generated') {
      if (!opts.dryRun) fs.rmSync(abs);
      res.removed.push(f);
    }
  }
  return res;
}

/** Regenerate quietly after a state change; never fails the calling command. */
export function regen(repo: Repo): string | null {
  try {
    const r = runGen(repo);
    return r.refused.length ? `lanes gen skipped hand-written files: ${r.refused.join(', ')} (move them aside, then \`lanes gen\`)` : null;
  } catch (e: any) {
    return `lanes gen failed: ${e.message}`;
  }
}
